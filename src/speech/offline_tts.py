"""Offline English speech synthesis using installed Windows SAPI voices."""

import base64
import os
import shutil
import subprocess
import tempfile
from pathlib import Path


_POWERSHELL_SCRIPT = r"""
$ErrorActionPreference = "Stop"
try {
    Add-Type -AssemblyName System.Speech
    $text = [Text.Encoding]::UTF8.GetString(
        [Convert]::FromBase64String($env:SINDHI_TTS_TEXT_B64)
    )
    $outputPath = [Text.Encoding]::UTF8.GetString(
        [Convert]::FromBase64String($env:SINDHI_TTS_OUTPUT_PATH_B64)
    )
    $synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
    try {
        $voice = $synth.GetInstalledVoices() |
            Where-Object { $_.Enabled -and $_.VoiceInfo.Culture.Name -like "en-*" } |
            Select-Object -First 1
        if ($null -eq $voice) {
            throw "No enabled offline English SAPI voice is installed."
        }
        $synth.SelectVoice($voice.VoiceInfo.Name)
        $synth.SetOutputToWaveFile($outputPath)
        $synth.Speak($text)
    }
    finally {
        $synth.Dispose()
    }
}
catch {
    [Console]::Error.WriteLine($_.Exception.Message)
    exit 1
}
"""


def synthesize_english_speech(text: str, timeout_seconds: int = 60) -> bytes:
    """Return WAV audio generated by an installed, local English SAPI voice."""
    if not text.strip():
        raise ValueError("English text is required for speech synthesis.")
    if os.name != "nt":
        raise RuntimeError("Offline SAPI speech synthesis is available only on Windows.")

    powershell = shutil.which("powershell.exe") or shutil.which("powershell")
    if powershell is None:
        raise RuntimeError("Windows PowerShell was not found; no speech audio was generated.")

    with tempfile.NamedTemporaryFile(prefix="sindhi_voice_", suffix=".wav", delete=False) as temp_file:
        output_path = Path(temp_file.name)

    encode = lambda value: base64.b64encode(value.encode("utf-8")).decode("ascii")
    command = [
        powershell,
        "-NoProfile",
        "-NonInteractive",
        "-ExecutionPolicy",
        "Bypass",
        "-Command",
        _POWERSHELL_SCRIPT,
    ]
    environment = os.environ.copy()
    environment["SINDHI_TTS_TEXT_B64"] = encode(text)
    environment["SINDHI_TTS_OUTPUT_PATH_B64"] = encode(str(output_path))

    try:
        try:
            result = subprocess.run(
                command,
                capture_output=True,
                text=True,
                timeout=timeout_seconds,
                check=False,
                env=environment,
            )
        except subprocess.TimeoutExpired as error:
            raise RuntimeError("Offline English speech synthesis timed out.") from error

        if result.returncode != 0:
            details = result.stderr.strip() or "PowerShell speech synthesis failed."
            raise RuntimeError(details)

        audio = output_path.read_bytes()
        if not audio.startswith(b"RIFF") or len(audio) <= 44:
            raise RuntimeError("Windows speech synthesis did not produce a valid WAV file.")
        return audio
    finally:
        if output_path.exists():
            output_path.unlink()
